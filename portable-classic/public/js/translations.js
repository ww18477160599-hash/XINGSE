// 核心转换引擎：无论输入何种中文组合、斜杠多选、自定义词，坚决彻底转换为 100% 纯正英文
function toEn(val) {
  if (!val) return '';
  if (typeof val !== 'string') return String(val);
  
  // 1. 如果完全不含中文，直接返回
  if (!/[\u4e00-\u9fa5]/.test(val)) return val.trim();

  // 2. 查字典直译
  if (XINGSE_EN_DICT[val] !== undefined) return XINGSE_EN_DICT[val];

  // 3. 处理斜杠多选项例如 "项链/耳环"、"锁骨/直角肩"
  if (val.includes('/')) {
    const subs = val.split('/').map(v => toEn(v.trim())).filter(Boolean);
    return subs.join(', ');
  }

  // 4. 处理带特定中文后缀的模式（如 "20–21岁" -> "20-21 years old"）
  if (val.endsWith('岁')) {
    return val.replace('岁', ' years old').replace('–', '-');
  }

  // 5. 递归词根替换
  let res = val;
  for (const [zh, en] of Object.entries(XINGSE_EN_DICT)) {
    if (zh && en && res.includes(zh)) {
      res = res.replaceAll(zh, ' ' + en + ' ');
    }
  }

  // 6. 终极防泄漏：彻底滤除任何残留的中文字符与中文标点
  res = res.replace(/[\u4e00-\u9fa5\u3000-\u303f\uff01-\uffee]/g, ' ').replace(/\s+/g, ' ').trim();
  return res;
}

